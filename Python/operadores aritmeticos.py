#Suma
a = 5
b = 3
suma = a + b
print("Suma:", suma)

#Resta
resta = a - b
print("Resta:", resta)

#Multiplicación
multiplicacion = a * b
print("Multiplicación:", multiplicacion)

#División
division = a / b
print("División:", division)

#Division entera
division_entera = a // b   
print("División entera:", division_entera)

#Modulo
modulo = a % b
print("Modulo:", modulo)

#Exponente
exponente = a ** b
print("Exponente:", exponente)

